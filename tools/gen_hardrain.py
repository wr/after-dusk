"""Generate src/hardrain_tables.inc: Hard Rain's rings.

A ring is the midpoint circle of radius r (0-9), each dot once. The program
XORs rings onto the screen a row at a time as 7-bit screen bytes, from tables
it builds in FXRAM at init: for every ring, every row and every bit position
s (0-6) of the centre within its byte, the row's 5 bytes covering byte columns
-2 to +2 of the centre's. This file holds the rows for s = 0 (4 bytes each,
the fifth is always clear), and where each ring's table for each s sits:

hr_rows   for ring r, rows dy = -r to r, 4 bytes: dot dx is bit (dx + 14) of
          the 35-bit row (byte (dx + 14) // 7, bit (dx + 14) % 7)
hr_tlo/hr_thi  for index r * 7 + s, the address of the ring's table in FXRAM:
          2r + 1 rows of 5 bytes, each the s = 0 row shifted s dots right
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAXR = 9
HR_TBL = 0x0800                 # the tables' place in FXRAM (fx_hardrain.s agrees)
HR_TBL_END = 0x1600             # the drop arrays start here


def ring(r):
    """The sample's midpoint circle of radius r, each dot once."""
    pts, seen = [], set()
    x, y, e = r, 0, 1 - r
    while x >= y:
        for p in ((x, y), (y, x), (-x, y), (-y, x), (x, -y), (y, -x), (-x, -y), (-y, -x)):
            if p not in seen:
                seen.add(p)
                pts.append(p)
        y += 1
        if e < 0:
            e += 2 * y + 1
        else:
            x -= 1
            e += 2 * (y - x) + 1
    return pts


def rows(r):
    """Ring r's rows, top to bottom, as 4 screen bytes each for s = 0."""
    out = []
    for dy in range(-r, r + 1):
        bits = [0] * 4
        for dx, ddy in ring(r):
            if ddy == dy:
                q = dx + 14
                bits[q // 7] |= 1 << (q % 7)
        out.append(bits)
    return out


def table_addr(r, s):
    return HR_TBL + 5 * (7 * r * r + s * (2 * r + 1))


def byte_lines(name, values, per=16):
    lines = [f"{name}:"]
    for i in range(0, len(values), per):
        lines.append("        .byte " + ", ".join(f"${v:02X}" for v in values[i:i + per]))
    return lines


def main():
    assert table_addr(MAXR, 7) <= HR_TBL_END, "the ring tables overrun the drop arrays"
    lines = ["; Generated by tools/gen_hardrain.py. Do not edit.",
             f"; Rings 0-{MAXR} for a centre at bit 0 of its byte: 4 bytes a row, rows top to bottom",
             "hr_rows:"]
    for r in range(MAXR + 1):
        for i, row in enumerate(rows(r)):
            lines.append("        .byte " + ", ".join(f"${v:02X}" for v in row)
                         + (f"     ; ring {r}" if i == 0 else ""))
    addrs = [table_addr(r, s) for r in range(MAXR + 1) for s in range(7)]
    lines.append("; Where ring r's table for centre bit s sits in FXRAM, index r * 7 + s")
    lines += byte_lines("hr_tlo", [a & 0xFF for a in addrs])
    lines += byte_lines("hr_thi", [a >> 8 for a in addrs])
    lines.append("")
    (ROOT / "src/hardrain_tables.inc").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
