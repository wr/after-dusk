"""Generate src/strings_tables.inc: String Theory's phase table.

str_amp  257 entries: round(159.8 |sin a|) for angle a (256 = a full turn), the size of the
         swing in how far round the screen's edge a string's far end lies (0.17 of the
         940-dot perimeter). The sign is the angle's half: + for 0-127, - for 128-255.
         Entry 256 repeats entry 0, so the effect can interpolate between a and a + 1.
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PERIM = 2 * (279 + 191)


def main():
    amp = [round(PERIM * 0.17 * abs(math.sin(a * math.pi / 128))) for a in range(257)]
    lines = ["; Generated by tools/gen_strings.py. Do not edit.", "str_amp:"]
    for i in range(0, len(amp), 16):
        lines.append("        .byte " + ", ".join(f"${v:02X}" for v in amp[i:i + 16]))
    (ROOT / "src/strings_tables.inc").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
