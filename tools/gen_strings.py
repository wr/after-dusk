"""Generate src/strings_tables.inc: String Theory's phase table.

str_amp_lo, str_amp_hi  129 entries: round(282 |sin a|) for angle a (256 = a full turn), the
         size of the swing in how far round the screen's edge a string's far end lies (0.3 of
         the 940-dot perimeter), 0-282, so two bytes. |sin| repeats every half turn, so the
         table covers one, indexed by the angle's low 7 bits; the sign is the angle's top bit
         (+ for 0-127, - for 128-255). Entry 128 repeats entry 0, so the effect can
         interpolate between a and a + 1.
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PERIM = 2 * (279 + 191)
SWING = 0.3


def rows(name, values):
    out = [f"{name}:"]
    for i in range(0, len(values), 16):
        out.append("        .byte " + ", ".join(f"${v:02X}" for v in values[i:i + 16]))
    return out


def main():
    amp = [round(PERIM * SWING * abs(math.sin(a * math.pi / 128))) for a in range(129)]
    lines = ["; Generated by tools/gen_strings.py. Do not edit."]
    lines += rows("str_amp_lo", [v & 0xFF for v in amp])
    lines += rows("str_amp_hi", [v >> 8 for v in amp])
    (ROOT / "src/strings_tables.inc").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
