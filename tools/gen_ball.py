"""Generate src/ball_tables.inc: Bouncing Ball's starting headings.

16 angles a evenly through 0.45-1.1 radians, 4 bytes each, in 1/64 dot a step:
  cos a * 3.8 * 1.1, sin a * 3.8 * 1.1   (x parts: x speeds are stretched 1.1)
  cos a * 3.8,       sin a * 3.8         (y parts)
The program turns the heading a quarter turn 0-3 times, which swaps the parts
and their signs, so the ball can head off in any of the four quadrants.
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEED = 3.8
XA = 1.1
ANGLES = 16
LO, HI = 0.45, 1.1
ONE = 64


def main():
    rows = []
    for i in range(ANGLES):
        a = LO + (i + 0.5) * (HI - LO) / ANGLES
        vals = [math.cos(a) * SPEED * XA, math.sin(a) * SPEED * XA,
                math.cos(a) * SPEED, math.sin(a) * SPEED]
        rows.append("        .byte " + ", ".join(f"{round(v * ONE)}" for v in vals)
                    + f"     ; {a:.3f}")
    text = "\n".join(["; Generated by tools/gen_ball.py. Do not edit.",
                      "; cos 4.18, sin 4.18, cos 3.8, sin 3.8 (1/64 dot a step) for each angle",
                      "bb_heads:", *rows, ""])
    (ROOT / "src/ball_tables.inc").write_text(text)


if __name__ == "__main__":
    main()
