"""Generate src/rose_tables.inc: Rose's offsets from the centre for each angle.

An angle is 256 steps to a turn; the program looks a table up by the whole step, so each entry
is taken half a step on, in the middle of the angles that share it. The loops (radius 18) are
half the ring (radius 36), so the program halves these for them.

rose_cx  1.1 * 36 cos   x (stretched 1.1: IIc dots are wider than tall)
rose_sy        36 sin   y
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
A, XA = 36, 1.1


def table(name, amp, f):
    values = [round(amp * f((a + 0.5) * math.pi / 128)) & 0xFF for a in range(256)]
    lines = [f"{name}:"]
    for i in range(0, 256, 16):
        lines.append("        .byte " + ", ".join(f"${v:02X}" for v in values[i:i + 16]))
    return "\n".join(lines)


def main():
    parts = [
        "; Generated by tools/gen_rose.py. Do not edit.",
        table("rose_cx", A * XA, math.cos),
        table("rose_sy", A, math.sin),
    ]
    (ROOT / "src/rose_tables.inc").write_text("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
