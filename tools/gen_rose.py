"""Generate src/rose_tables.inc: Rose's tables, after the original After Dark Rose.

Sines are magnitudes, 255 = 1 (the program takes the sign from the angle's half turn):
rose_s128  |sin| of 128 steps to a turn, for sin(A u) and cos(A u)
rose_s240  |sin| of 240 steps to a turn (1.5 degrees), for sin(t + u) and cos(t + u)

The values A, B and C glide between:
rose_a8    8 A for A = 0, 1, 4, 9, 16 (8 A is what the dot's angle index steps by)
rose_bl/h  B, signed, 8192 = 1: -1.28 + 0.16 (i >> 1) + 0.04 (i & 1) for i < 32, then -1.20 + ...
rose_cl/h  C = 42 sqrt(i) 10/57 dots for i = 0-31 (42 = 4/9 of the half-height), 8.8
rose_cxl/h 1.1 C, 8.8 (x is stretched 1.1: IIc dots are wider than tall)
C and 1.1 C carry 256/255 too, so that C x sin magnitude / 256 is C sin.
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
XA = 1.1
A_TAB = (0, 1, 4, 9, 16)
B_TAB = ([(-128 + 16 * (i >> 1) + 4 * (i & 1)) / 100 for i in range(32)]
         + [(-120 + 16 * (i >> 1) + 4 * (i & 1)) / 100 for i in range(32)])
C_TAB = [42 * math.sqrt(i) * 10 / 57 for i in range(32)]
B_ONE = 8192
SINE = 255


def c_fixed(i, stretch=1.0):
    return round(stretch * C_TAB[i] * 256 / SINE * 256)


def byte_rows(name, values):
    lines = [f"{name}:"]
    for i in range(0, len(values), 16):
        lines.append("        .byte " + ", ".join(f"${v & 0xFF:02X}" for v in values[i:i + 16]))
    return "\n".join(lines)


def words(name, values):
    return "\n".join([byte_rows(name + "l", [v & 0xFF for v in values]),
                      byte_rows(name + "h", [(v >> 8) & 0xFF for v in values])])


def main():
    parts = [
        "; Generated by tools/gen_rose.py. Do not edit.",
        byte_rows("rose_s128", [round(SINE * abs(math.sin(2 * math.pi * i / 128))) for i in range(128)]),
        byte_rows("rose_s240", [round(SINE * abs(math.sin(2 * math.pi * i / 240))) for i in range(240)]),
        byte_rows("rose_a8", [8 * a for a in A_TAB]),
        words("rose_b", [round(b * B_ONE) for b in B_TAB]),
        words("rose_c", [c_fixed(i) for i in range(32)]),
        words("rose_cx", [c_fixed(i, XA) for i in range(32)]),
    ]
    (ROOT / "src/rose_tables.inc").write_text("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
