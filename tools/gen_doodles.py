"""Generate src/doodles_tables.inc: Doodles' tables (they live in its overlay).

dd_sa, dd_sb      256 entries: 80 sin and 47 sin of angle a (256 = a full turn), signed;
                  a doodle's wobble is dd_sa[a] + dd_sb[b], 0.63 and 0.37 of 127
dd_cxl, dd_cxh    cell centres across: entry (cols - 4) * 8 + c, for 4-8 columns
dd_cyt            cell centres down: entry (rows - 3) * 8 + r, for 3-6 rows
dd_ampx, dd_ampy  the doodle's reach, 0.34 of the cell's width and 0.38 of its height,
                  as a multiplier: offset = wobble * amp / 256 (entry cols - 4, rows - 3)
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
W, H = 280, 192
COLS = range(4, 9)
ROWS = range(3, 7)


def table(name, values):
    lines = [f"{name}:"]
    for i in range(0, len(values), 16):
        lines.append("        .byte " + ", ".join(f"${v & 0xFF:02X}" for v in values[i:i + 16]))
    return "\n".join(lines)


def sine(amp):
    return [round(amp * math.sin(a * math.pi / 128)) for a in range(256)]


def centres(n, size, stride):
    out = []
    for k in n:
        row = [int((c + 0.5) * size / k + 0.5) for c in range(k)]
        out += row + [0] * (stride - k)
    return out


def main():
    cx = centres(COLS, W, 8)
    parts = [
        "; Generated by tools/gen_doodles.py. Do not edit.",
        table("dd_sa", sine(80)),
        table("dd_sb", sine(47)),
        table("dd_cxl", [x & 0xFF for x in cx]),
        table("dd_cxh", [x >> 8 for x in cx]),
        table("dd_cyt", centres(ROWS, H, 8)),
        table("dd_ampx", [round(0.34 * W / k * 256 / 127) for k in COLS]),
        table("dd_ampy", [round(0.38 * H / k * 256 / 127) for k in ROWS]),
    ]
    (ROOT / "src/doodles_tables.inc").write_text("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
