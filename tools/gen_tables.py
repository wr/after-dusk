"""Generate src/tables.inc: lookup tables for hi-res drawing.

row_lo/row_hi   192 entries: page-1 address of each row's first byte
xbyte_lo/xbit_lo/xmod_lo 256 entries: for x 0-255, byte within the row, bit mask, x mod 7
xbyte_hi/xbit_hi/xmod_hi  80 entries: the same for x 256-335 (past 279 only the
                          sprite engine uses them, for cells offset to the right)
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def row_base(y):
    return 0x2000 + (y & 7) * 0x400 + ((y >> 3) & 7) * 0x80 + (y >> 6) * 0x28


def table(name, values):
    lines = [f"{name}:"]
    for i in range(0, len(values), 16):
        lines.append("        .byte " + ", ".join(f"${v:02X}" for v in values[i:i + 16]))
    return "\n".join(lines)


def main():
    rows = [row_base(y) for y in range(192)]
    xs_lo = range(256)
    xs_hi = range(256, 336)
    parts = [
        "; Generated by tools/gen_tables.py. Do not edit.",
        table("row_lo", [r & 0xFF for r in rows]),
        table("row_hi", [r >> 8 for r in rows]),
        table("xbyte_lo", [x // 7 for x in xs_lo]),
        table("xbit_lo", [1 << (x % 7) for x in xs_lo]),
        table("xmod_lo", [x % 7 for x in xs_lo]),
        table("xbyte_hi", [x // 7 for x in xs_hi]),
        table("xbit_hi", [1 << (x % 7) for x in xs_hi]),
        table("xmod_hi", [x % 7 for x in xs_hi]),
        "; Warp: v >> 4 and v >> 5 of a signed 8.8 value, as two lookups and an OR:",
        ";   (hi:lo) >> n = sarN[hi] : (shlM[hi] | shrN[lo]), M = 8 - n",
        table("sar4", [((h - 256 if h & 0x80 else h) >> 4) & 0xFF for h in range(256)]),
        table("shl4", [(h << 4) & 0xF0 for h in range(256)]),
        table("shr4", [lo >> 4 for lo in range(256)]),
        table("sar5", [((h - 256 if h & 0x80 else h) >> 5) & 0xFF for h in range(256)]),
        table("shl3", [(h << 3) & 0xF8 for h in range(256)]),
        table("shr5", [lo >> 5 for lo in range(256)]),
        "; Can of Worms: per-step motion for heading a (0-255 = a full turn), 8.8",
        ";   x: 2 cos, y: 1.7 sin (y grows downwards)",
        table("wvx_lo", [round(2 * math.cos(a * math.pi / 128) * 256) & 0xFF for a in range(256)]),
        table("wvx_hi", [(round(2 * math.cos(a * math.pi / 128) * 256) >> 8) & 0xFF for a in range(256)]),
        table("wvy_lo", [round(1.7 * math.sin(a * math.pi / 128) * 256) & 0xFF for a in range(256)]),
        table("wvy_hi", [(round(1.7 * math.sin(a * math.pi / 128) * 256) >> 8) & 0xFF for a in range(256)]),
    ]
    (ROOT / "src/tables.inc").write_text("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
