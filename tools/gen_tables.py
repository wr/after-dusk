"""Generate src/tables.inc: lookup tables for hi-res drawing.

row_lo/row_hi   192 entries: page-1 address of each row's first byte
xbyte_lo/xbit_lo 256 entries: for x 0-255, byte within the row and its bit mask
xbyte_hi/xbit_hi  24 entries: the same for x 256-279
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def row_base(y):
    return 0x2000 + (y & 7) * 0x400 + ((y >> 3) & 7) * 0x80 + (y >> 6) * 0x28


def table(name, values):
    lines = [f"{name}:"]
    for i in range(0, len(values), 16):
        lines.append("        .byte " + ", ".join(f"${v:02X}" for v in values[i:i + 16]))
    return "\n".join(lines)


def main():
    rows = [row_base(y) for y in range(192)]
    xs_lo = range(256)
    xs_hi = range(256, 280)
    parts = [
        "; Generated by tools/gen_tables.py. Do not edit.",
        table("row_lo", [r & 0xFF for r in rows]),
        table("row_hi", [r >> 8 for r in rows]),
        table("xbyte_lo", [x // 7 for x in xs_lo]),
        table("xbit_lo", [1 << (x % 7) for x in xs_lo]),
        table("xbyte_hi", [x // 7 for x in xs_hi]),
        table("xbit_hi", [1 << (x % 7) for x in xs_hi]),
    ]
    (ROOT / "src/tables.inc").write_text("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
