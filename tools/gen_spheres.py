"""Generate src/spheres_tables.inc: Spheres' tables, after the original After Dark Spheres.

A sphere is 34 circles, k = 0..33, drawn one at a time, each smaller and brighter than the
last and nudged up and to the right, towards the highlight. For a sphere of radius r:
sp_tr   circle k's radius is r sqrt(1 - k/33): sqrt(1 - k/33), 256 = 1 (k = 0 is r itself)
sp_to   its centre moves up r 3/20 sqrt(k/33) dots: in quarter dots per dot of r, 256 = 1
sp_tox  and right 1.1 times that (the IIc's dots are a little narrower than tall)
sp_tl   its grey, round((24 + 7k) / 255 x 16): how many of every 16 dots are lit
sp_hx   a half-width of h quarter dots on the y scale is floor(1.1 (h + 1/2)) on the x
        scale, for h = 0..176 (the biggest sphere, r = 44 as RMAX in fx_spheres.s, is 176
        quarter dots), then sp_hx_end
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
XA = 1.1
K = 34
RMAX4 = 4 * 44                  # RMAX in src/fx_spheres.s


def byte_rows(name, values):
    assert all(0 <= v <= 255 for v in values), name
    lines = [f"{name}:"]
    for i in range(0, len(values), 16):
        lines.append("        .byte " + ", ".join(f"${v:02X}" for v in values[i:i + 16]))
    return "\n".join(lines)


def tables():
    tr = [0] + [round(256 * math.sqrt(1 - k / 33)) for k in range(1, K)]
    to = [round(256 * 4 * 3 / 20 * math.sqrt(k / 33)) for k in range(K)]
    tox = [round(256 * 4 * 3 / 20 * XA * math.sqrt(k / 33)) for k in range(K)]
    tl = [round((24 + 7 * k) / 255 * 16) for k in range(K)]
    hx = [math.floor(XA * (h + 0.5)) for h in range(RMAX4 + 1)]
    return dict(sp_tr=tr, sp_to=to, sp_tox=tox, sp_tl=tl, sp_hx=hx)


def main():
    out = ["; Generated by tools/gen_spheres.py; do not edit."]
    out += [byte_rows(name, values) for name, values in tables().items()]
    out.append("sp_hx_end:")
    (ROOT / "src/spheres_tables.inc").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
